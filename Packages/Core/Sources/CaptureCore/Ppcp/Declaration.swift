//  Declaration.swift
//  The device's `Peer` declaration (`CORE` §5.2), built out of `libppcp`'s own
//  structs from what the real capture stack enumerated.
//
//  ⚠ **REQ-PORT-11 in one sentence: the Swift capability types are now *views
//  over* the library's structs, not a parallel vocabulary.** `DeviceCapability`,
//  `VideoMode`, `Lens` and `MeasuredCapability` describe the device for a
//  *screen*; `ppcp_peer_desc`, `ppcp_source`, `ppcp_capture_profile` and
//  `ppcp_measured_capability` describe it for a *peer*. This file is the one
//  place the first becomes the second, and there is deliberately no second place:
//  two translations drift, and the drift is invisible because each half looks
//  right on its own.
//
//  ⛔ **Every structural invariant below is the library's, not this file's.**
//  I22 (`frame_start_to_exposure_offset_ns` present iff `nominal_frame_start`) is
//  held by there being two constructors in `timing.h` and only one of them taking
//  an offset. I31 (provenance on every unmeasured constant) is held by provenance
//  being a *parameter* of both constructors. I28 (`measured` means measured) is
//  held by `ppcp_measured_capability_make` taking a method and a duration and by
//  there being no constructor from a profile or a table. This file cannot
//  produce the malformed shapes even by trying, which is the whole reason the
//  declaration is assembled through the C API rather than encoded in Swift.
//
//  Spec: `CORE` §5.2, §5.3, §5.6, §5.6.1, §5.7, §5.8; `CONF` CT-I4, CT-I19,
//  CT-I22, CT-I28, CT-I31, CT-S7 1–3. Decisions: A12, A13.

import Foundation
import CPPCP

// MARK: - Timebases

/// `CORE` §5.3 — a clock this peer declares, in neutral terms.
///
/// ⚠ Every field is the platform's to *report*, not this layer's to assume:
/// `resolution_ns` comes from `mach_timebase_info` on iOS and from something else
/// on the next platform, and `kind` is a property of the specific clock the
/// samples are in. See `PpcpTimebases` in `Sources/Platform` for the readings and
/// for the finding about which clock AVFoundation actually stamps with.
public struct PpcpTimebaseDeclaration: Sendable, Hashable {

    public enum Kind: Sendable, Hashable {
        /// Halts across device sleep.
        case monotonic
        /// Does not.
        case continuous
        /// Subject to jumps, and **label-only** (5.3b, I15).
        case wall
    }

    public let id: String
    public let kind: Kind
    public let epochStable: Bool
    public let resolutionNs: Int64
    /// `CORE` 5.3 — "opaque and informational, e.g. `CMClockGetHostTimeClock`.
    /// MUST NOT be interpreted."
    public let origin: String?

    public init(id: String, kind: Kind, epochStable: Bool,
                resolutionNs: Int64, origin: String? = nil) {
        self.id = id
        self.kind = kind
        self.epochStable = epochStable
        self.resolutionNs = resolutionNs
        self.origin = origin
    }

    var cKind: ppcp_timebase_kind {
        switch kind {
        case .monotonic: PPCP_TB_MONOTONIC
        case .continuous: PPCP_TB_CONTINUOUS
        case .wall: PPCP_TB_WALL
        }
    }
}

// MARK: - Viewpoint

/// `CORE` 5.6e — "declares **how it was arrived at** … and carries `confidence`
/// **only** in the second case."
///
/// ⛔ The two cases are separate values with separate payloads, so a `declared`
/// viewpoint has nowhere to put a confidence. 5.6e: "A person who states 'down
/// the line' is not expressing a probability, and requiring a number there would
/// be asking a peer to invent one, which is the pattern I28 and I31 exist to
/// prevent."
public enum PpcpViewpoint: Sendable, Hashable {
    /// A user or installer stated it.
    case declared(label: String)
    /// The peer worked it out, and only then a confidence.
    case classified(label: String, confidence: Double)
}

// MARK: - What a declaration is built from

/// Everything the declaration needs, in neutral terms. ⚠ Assembled by the
/// platform layer from the real capture stack (`AVFoundationCaptureDevice`) and
/// the model's `DeviceProfiles.json` entry — never from a spec sheet (REQ-FPS-1)
/// and never from `product` (5.2c, I19).
public struct PpcpDeclarationInput: Sendable {

    /// `CORE` 5.2.1a — generated by the peer and persisted in its own store.
    /// ⛔ 5.2.1b: never a platform device identifier or an advertising identifier.
    public var peerId: String
    /// `CORE` §10.1 — the wire version this peer speaks. Asked of the library.
    public var protocolVersion: String
    /// `CORE` 5.2 — MUST include `core`. Plan §2: this application's set.
    public var profiles: [String]

    public var timebases: [PpcpTimebaseDeclaration]
    /// Which of them every Source is on. `CORE` 5.3 / I4: "Two Sources on the
    /// same clock reference the **same** `Timebase.id`."
    public var captureTimebaseId: String

    public var capability: DeviceCapability
    public var timing: PpcpDeviceTimingProfile

    /// `CORE` 5.7 `format.codec`. See the ⚠ where it is written.
    public var clipCodec: String

    public var declaresMicrophone: Bool
    public var declaresIMU: Bool
    public var viewpoint: PpcpViewpoint?

    /// `CORE` 5.2 `product` — informational. ⛔ 5.2c: a peer MUST NOT infer any
    /// capability, convention or geometry from it (I19), which is why it is last
    /// and why nothing in this file reads it back.
    public var product: (vendor: String, model: String, version: String)?

    public init(peerId: String,
                protocolVersion: String = PpcpLibrary.wireVersion,
                profiles: [String],
                timebases: [PpcpTimebaseDeclaration],
                captureTimebaseId: String,
                capability: DeviceCapability,
                timing: PpcpDeviceTimingProfile,
                clipCodec: String,
                declaresMicrophone: Bool = true,
                declaresIMU: Bool = true,
                viewpoint: PpcpViewpoint? = nil,
                product: (vendor: String, model: String, version: String)? = nil) {
        self.peerId = peerId
        self.protocolVersion = protocolVersion
        self.profiles = profiles
        self.timebases = timebases
        self.captureTimebaseId = captureTimebaseId
        self.capability = capability
        self.timing = timing
        self.clipCodec = clipCodec
        self.declaresMicrophone = declaresMicrophone
        self.declaresIMU = declaresIMU
        self.viewpoint = viewpoint
        self.product = product
    }
}

